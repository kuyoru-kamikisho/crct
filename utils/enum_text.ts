export type EnumTextKey = keyof typeof EnumText;

/**
 * 从文案池中取一条回复（单条直接返回，多条随机）
 */
export function pickReply(pool: ReplyPool): string {
  if (typeof pool === 'string') return pool;
  if (pool.length === 0) return EnumText.unknown[0];
  const i = Math.floor(Math.random() * pool.length);
  return pool[i]!;
}
